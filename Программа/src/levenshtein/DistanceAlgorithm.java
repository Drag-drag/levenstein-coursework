package levenshtein;

/**
 * Общий интерфейс для всех реализаций алгоритма вычисления
 * расстояния Левенштейна. Позволяет сравнивать реализации
 * между собой в тестах и бенчмарках.
 */
public interface DistanceAlgorithm {

    /**
     * Вычисляет расстояние Левенштейна между строками a и b.
     *
     * @param a первая строка
     * @param b вторая строка
     * @return минимальное число вставок, удалений и замен
     */
    int distance(String a, String b);

    /**
     * @return человекочитаемое название реализации
     */
    String name();
}
