def table(caption, headers, rows, widths=None, font_size=12,
          align_first_left=True):
    c = doc.add_paragraph(style="Caption2")
    c.paragraph_format.first_line_indent = Cm(0)
    c.paragraph_format.space_before = Pt(6)
    c.paragraph_format.space_after = Pt(4)
    c.add_run(caption)

    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False

    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ""
        p = hdr[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.line_spacing = 1.0
        r = p.add_run(h)
        r.bold = True
        r.font.size = Pt(font_size)

    for row in rows:
        cells = t.add_row().cells
        for i, value in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.line_spacing = 1.0
            if i == 0 and align_first_left:
                p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            else:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = p.add_run(str(value))
            r.font.size = Pt(font_size)

    if widths:
        for i, w in enumerate(widths):
            t.columns[i].width = Cm(w)
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)

    doc.add_paragraph().paragraph_format.space_after = Pt(0)


def listing(caption, code, size=8.5):
    c = doc.add_paragraph(style="Caption2")
    c.paragraph_format.first_line_indent = Cm(0)
    c.paragraph_format.space_before = Pt(6)
    c.paragraph_format.space_after = Pt(2)
    c.add_run(caption)

    for line in code.rstrip("\n").split("\n"):
        p = doc.add_paragraph(style="CodeBlock")
        p.paragraph_format.line_spacing = 1.0
        run = p.add_run(line if line else " ")
        run.font.size = Pt(size)
        pPr = p._p.get_or_add_pPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear")
        shd.set(qn("w:fill"), "F4F4F4")
        pPr.append(shd)


